// Packs the narrator (art-src/audio/intro_N.mp3, N = position in INTRO_LINES) into src/js/05-vo.js.   node tools/vo.mjs
// Also stores how long each sentence lasts (VO_DUR, seconds) and when it starts and ends in the whole narration (VO_AT):
// the subtitles of every language are typed against these times. Needs ffprobe (apt install ffmpeg).
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
const dir = new URL('../art-src/audio/', import.meta.url), out = [], dur = [];
for (let i = 0; fs.existsSync(new URL(`intro_${i}.mp3`, dir)); i++) {
  const f = new URL(`intro_${i}.mp3`, dir);
  out.push("'data:audio/mpeg;base64," + fs.readFileSync(f).toString('base64') + "'");
  dur.push(+(+execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f.pathname]).toString().trim()).toFixed(2));
}
let t = 0; const GAP = 0.45, at = dur.map((d) => { const a = [+t.toFixed(2), +(t + d).toFixed(2)]; t += d + GAP; return a; });
fs.writeFileSync(new URL('../src/js/05-vo.js', import.meta.url),
  '/* GENERATED by tools/vo.mjs from art-src/audio/intro_N.mp3 — the narrator of the opening (English, heard in every language) */\n' +
  'const VO_DUR = ' + JSON.stringify(dur) + ';            // seconds, one per sentence\n' +
  'const VO_AT = ' + JSON.stringify(at) + ';             // [start, end] of each sentence in the whole narration\n' +
  'const VO_SRC = [\n' + out.join(',\n') + '\n];\n');
console.log('voice lines:', out.length, '| total', t.toFixed(1) + ' s', '|', dur.join(' '));
