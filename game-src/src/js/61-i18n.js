/* Latin words, addresses and handles inside Persian or Arabic are wrapped in LRI…PDI (U+2066…U+2069), and whatever is
   filled into {0} in FSI…PDI, so that a dash, a bracket or a "·" next to them never jumps to the wrong side. */
const BIDI = { LRI: '\u2066', FSI: '\u2068', PDI: '\u2069' };
function bidiWrap(s) {
  return s.split(/(<[^>]+>|\{\w\})/).map((part, i) => (i % 2 ? part :
    part.replace(/[A-Za-z@+#][A-Za-z0-9@._:\/+#&'’%-]*(?:[ ][A-Za-z#&][A-Za-z0-9@._:\/+#&'’%-]*)*/g, (m) => (/[A-Za-z]|^\+\d/.test(m) ? BIDI.LRI + m + BIDI.PDI : m)))).join('');
}
/* id in, text out. Unknown ids come back unchanged, so a plain name can be passed through tr() safely. */
function tr(id, ...fill) {
  if (typeof id !== 'string') return id;
  let s = STR[LANG] && STR[LANG][id];
  if (s == null || s === '') s = STR.en[id];
  if (s == null) return id;
  const rtl = !!RTL[LANG];
  if (s.indexOf('{score}') >= 0) s = s.split('{score}').join(trNum(G.score));
  if (rtl) s = bidiWrap(s);
  if (fill.length) s = s.replace(/\{(\d)\}/g, (m, i) => { const v = fill[i] == null ? '' : String(fill[i]); return (rtl || /[\u0590-\u08ff]/.test(v)) && v && !/^[\d\u06f0-\u06f9\u0660-\u0669\s.,٬٫]*$/.test(v) && v.indexOf('<') < 0 && v.indexOf('\u2068') < 0 ? BIDI.FSI + v + BIDI.PDI : v; });
  if (s.indexOf('{N}') >= 0) s = s.split('{N}').join(Redact.text());
  return s;
}
/* 30 -> ۳۰ (Persian) or ٣٠ (Arabic); unchanged elsewhere. Never used for addresses, handles or phone numbers. */
function trNum(n) {
  const d = LANG === 'fa' ? '۰۱۲۳۴۵۶۷۸۹' : LANG === 'ar' ? '٠١٢٣٤٥٦٧٨٩' : null;
  return d ? String(n).replace(/\d/g, (c) => d[c]) : String(n);
}
/* how the typewriter cuts a line: one visible character at a time (a letter with its marks),
   or one word at a time in Persian and Arabic so that joined letters never change shape while they appear */
function typeSteps(s) {
  const g = s.match(/(?:[\ud800-\udbff][\udc00-\udfff]|[\s\S])[\u0300-\u036f\u064b-\u065f\u0670\u200c\u200d\u3099\u309a\ufe0f]*/g) || [];
  const ends = []; let p = 0;
  for (const c of g) { p += c.length; ends.push(p); }
  if (!RTL[LANG]) return ends;
  let last = 0;
  return ends.map((e, i) => { if (i === g.length - 1 || /\s/.test(g[i + 1])) last = e; return last; });
}

/* text that lives in the page: <b data-i18n="ui.score"></b>, data-i18n-ph (placeholder), data-i18n-title (tooltip) */
const I18N = {
  apply(root) {
    if (!root || !root.querySelectorAll) return;
    const each = (attr, fn) => { if (root.hasAttribute && root.hasAttribute(attr)) fn(root, root.getAttribute(attr)); root.querySelectorAll('[' + attr + ']').forEach((n) => fn(n, n.getAttribute(attr))); };
    each('data-i18n', (n, id) => { const t = tr(id); if (t.indexOf('<') >= 0) n.innerHTML = t; else if (n.textContent !== t || t.indexOf(Redact.MARK) >= 0) n.textContent = t; Redact.fix(n); });
    each('data-i18n-ph', (n, id) => { n.placeholder = Redact.plain(tr(id)); });
    each('data-i18n-title', (n, id) => { const t = Redact.plain(tr(id)).replace(/[\u2066-\u2069]/g, ''); n.title = t; n.setAttribute('aria-label', t); });
  }
};
new MutationObserver((ms) => {
  for (const m of ms) {
    if (m.type === 'characterData') { Redact.fix(m.target); continue; }
    m.addedNodes.forEach((n) => {
      if (n.nodeType === 3) { Redact.fix(n); return; }
      if (n.nodeType === 1 && !n.classList.contains('redacted')) { I18N.apply(n); Redact.fix(n); }
    });
  }
}).observe(el('app'), { subtree: true, childList: true, characterData: true });

