const LANGS = ['en', 'fa', 'ar', 'ru', 'ja'];
const LANG_LABEL = { en: 'EN', fa: 'فا', ar: 'ع', ru: 'РУ', ja: '日' };                       // the round language button
const LANG_NAME = { en: 'English', fa: 'فارسی', ar: 'العربية', ru: 'Русский', ja: '日本語' };   // the first screen
const RTL = { fa: true, ar: true };
const LANG_KEY = 'rune-architect-lang';
let LANG = 'en';
try {
  const s = localStorage.getItem(LANG_KEY), n = (navigator.language || 'en').slice(0, 2).toLowerCase();
  LANG = LANGS.includes(s) ? s : LANGS.includes(n) ? n : 'en';
} catch (e) {}

/* ---------------- the name ----------------
   In STR his name is written {N}. Until the Throne falls (G.flags.named) it is never put on the page:
   tr() hands out a private marker, and the watcher below turns that marker into
   <span class="redacted" data-name>…decoy letters under a scribble…</span>.
   After the reveal tr() writes the real name, in the spelling of the current language.
   The letters are stored shifted by three, so a search of the file for the name finds nothing. */
const NM = { en: [86,107,100,124,100,113], fa: [1591,1578,1743,1578,1609], ar: [1591,1578,1613,1578,1609], ru: [1067,1075,1106,1088], ja: [12474,12518,12519,12534] };
const Redact = {
  MARK: '\ue000',
  shown() { return typeof G !== 'undefined' && !!(G.flags && G.flags.named); },
  name(lang) { return String.fromCharCode(...(NM[lang] || NM.en).map((c) => c - 3)); },
  text() { return this.shown() ? this.name(LANG) : this.MARK; },
  plain(s) { return String(s).split(this.MARK).join('▒▒▒▒▒'); },                 // for tooltips and placeholders, which cannot hold a span
  span() {
    const n = document.createElement('span');
    n.className = 'redacted'; n.setAttribute('data-name', ''); n.setAttribute('aria-label', '▒▒▒▒▒');
    n.textContent = (STR[LANG] && STR[LANG]['name.decoy']) || STR.en['name.decoy'];
    return n;
  },
  /* every text node under root that still holds the marker gets the scribbled span instead */
  fix(root) {
    if (!root) return;
    const todo = [];
    if (root.nodeType === 3) { if (root.data.indexOf(this.MARK) >= 0) todo.push(root); }
    else if (root.nodeType === 1 && root.textContent.indexOf(this.MARK) >= 0) {
      const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
      for (let n = w.nextNode(); n; n = w.nextNode()) if (n.data.indexOf(this.MARK) >= 0) todo.push(n);
    }
    for (const n of todo) {
      if (!n.parentNode) continue;
      const parts = n.data.split(this.MARK), f = document.createDocumentFragment();
      parts.forEach((t, i) => { if (i) f.appendChild(this.span()); if (t) f.appendChild(document.createTextNode(t)); });
      n.parentNode.replaceChild(f, n);
    }
  },
  /* redraw every text on the page (after the reveal, or after a save is loaded) */
  refresh() {
    I18N.apply(el('app'));
    if (typeof hudSync === 'function') hudSync();
    document.dispatchEvent(new Event('langchange'));
  }
};


